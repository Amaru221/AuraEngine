pub fn strings(lang: Lang) -> &'static Strings {
    match lang {
        Lang::En => &EN,
        Lang::Es => &ES,
        Lang::Fr => &FR,
    }
}

pub fn scaling_name(scaling: Scaling, s: &Strings) -> &'static str {
    match scaling {
        Scaling::Fit => s.fit,
        Scaling::Fill => s.fill,
        Scaling::Stretch => s.stretch,
        Scaling::Center => s.center,
    }
}

pub fn kind_label(kind: crate::config::MediaKind, s: &Strings) -> &'static str {
    match kind {
        crate::config::MediaKind::Image => s.media_image,
        crate::config::MediaKind::Video => s.media_video,
    }
}

